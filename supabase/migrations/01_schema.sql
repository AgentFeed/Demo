-- Public discovery tables are readable; writes should be service-role/admin
-- operations in the deployed FastAPI service.
drop policy if exists jobs_read on public.jobs;
create policy jobs_read on public.jobs for select using (true);
drop policy if exists schemes_read on public.schemes;
create policy schemes_read on public.schemes for select using (true);
drop policy if exists startups_read on public.startups;
create policy startups_read on public.startups for select using (true);
drop policy if exists startup_applications_owner_or_applicant on public.startup_applications;
create policy startup_applications_owner_or_applicant on public.startup_applications for all
  using (auth.uid() = applicant_id or exists (select 1 from public.startups where startups.id = startup_applications.startup_id and startups.owner_id = auth.uid()))
  with check (auth.uid() = applicant_id);
drop policy if exists social_edges_read on public.social_edges;
create policy social_edges_read on public.social_edges for select using (true);

drop policy if exists users_self on public.users;
create policy users_self on public.users for all using (auth.uid() = id) with check (auth.uid() = id);
drop policy if exists interactions_self on public.interactions;
create policy interactions_self on public.interactions for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists impressions_self on public.impressions;
create policy impressions_self on public.impressions for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists memory_self on public.agent_memory;
create policy memory_self on public.agent_memory for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- pgvector candidate-generation functions used by the Matcher agent. The
-- FastAPI service calls these through Supabase RPC, keeping retrieval in the
-- database instead of loading the whole catalogue into Python.
create or replace function public.match_jobs(query_embedding vector(384), match_count int default 100)
returns setof public.jobs
language sql stable security definer set search_path = public
as $$
  select jobs.*
  from public.jobs
  where jobs.embedding is not null
  order by jobs.embedding <=> query_embedding
  limit greatest(1, least(match_count, 100));
$$;

create or replace function public.match_schemes(query_embedding vector(384), match_count int default 50)
returns setof public.schemes
language sql stable security definer set search_path = public
as $$
  select schemes.*
  from public.schemes
  where schemes.embedding is not null
  order by schemes.embedding <=> query_embedding
  limit greatest(1, least(match_count, 50));
$$;

create or replace function public.match_startups(query_embedding vector(384), match_count int default 20)
returns setof public.startups
language sql stable security definer set search_path = public
as $$
  select startups.*
  from public.startups
  where startups.embedding is not null and startups.status = 'open'
  order by startups.embedding <=> query_embedding
  limit greatest(1, least(match_count, 20));
$$;

create or replace function public.match_users(query_embedding vector(384), match_count int default 30, exclude_user_id uuid default null)
returns setof public.users
language sql stable security definer set search_path = public
as $$
  select users.*
  from public.users
  where users.interest_embedding is not null and (exclude_user_id is null or users.id <> exclude_user_id)
  order by users.interest_embedding <=> query_embedding
  limit greatest(1, least(match_count, 30));
$$;

grant execute on function public.match_jobs(vector, int) to anon, authenticated, service_role;
grant execute on function public.match_schemes(vector, int) to anon, authenticated, service_role;
grant execute on function public.match_startups(vector, int) to anon, authenticated, service_role;
grant execute on function public.match_users(vector, int, uuid) to anon, authenticated, service_role;
