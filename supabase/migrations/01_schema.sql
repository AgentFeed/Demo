-- Bharat Career Twin production-shaped schema.
-- The local API uses SQLite for zero-credential demos; this migration is the
-- Supabase/Postgres contract the repositories are designed to target.

create extension if not exists vector;
create extension if not exists pgcrypto;

create table if not exists public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text,
  avatar_url text,
  city text,
  state text,
  lat double precision,
  lng double precision,
  experience_level text,
  skills text[] not null default '{}',
  education text,
  raw_resume_text text,
  resume_json jsonb,
  ats_score int not null default 68,
  interest_embedding vector(384),
  hate_embedding vector(384),
  created_at timestamptz not null default now()
);

create table if not exists public.user_interests (
  user_id uuid references public.users(id) on delete cascade,
  tag text not null,
  weight double precision not null default 1,
  created_at timestamptz not null default now(),
  primary key (user_id, tag)
);

create table if not exists public.user_hates (
  user_id uuid references public.users(id) on delete cascade,
  tag text not null,
  weight double precision not null default 1,
  created_at timestamptz not null default now(),
  primary key (user_id, tag)
);

create table if not exists public.jobs (
  id uuid primary key default gen_random_uuid(),
  freehire_id text unique,
  title text not null,
  company text,
  location_city text,
  location_state text,
  skills text[] not null default '{}',
  description text,
  experience_min int,
  experience_max int,
  salary_min int,
  salary_max int,
  salary_text text,
  job_type text,
  source text not null default 'kaggle_india',
  source_url text,
  board text,
  provider text,
  posted_at timestamptz not null default now(),
  likes_count int not null default 0,
  saves_count int not null default 0,
  embedding vector(384)
);
create index if not exists jobs_embedding_idx on public.jobs using hnsw (embedding vector_cosine_ops);
create index if not exists jobs_source_idx on public.jobs (source);
create index if not exists jobs_posted_idx on public.jobs (posted_at desc);

create table if not exists public.schemes (
  id uuid primary key default gen_random_uuid(),
  scheme_name text not null,
  ministry text,
  category text,
  benefits text,
  eligibility_json jsonb not null default '{}',
  application_url text,
  state text,
  posted_at timestamptz not null default now(),
  likes_count int not null default 0,
  embedding vector(384)
);
create index if not exists schemes_embedding_idx on public.schemes using hnsw (embedding vector_cosine_ops);

create table if not exists public.startups (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid references public.users(id) on delete set null,
  title text not null,
  description text not null,
  category text,
  skills_needed text[] not null default '{}',
  location_city text,
  status text not null default 'open',
  embedding vector(384),
  likes_count int not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists startups_embedding_idx on public.startups using hnsw (embedding vector_cosine_ops);

create table if not exists public.startup_applications (
  id bigint generated by default as identity primary key,
  startup_id uuid references public.startups(id) on delete cascade,
  applicant_id uuid references public.users(id) on delete cascade,
  message text not null,
  skill_offer text[] not null default '{}',
  status text not null default 'received',
  created_at timestamptz not null default now()
);
create index if not exists startup_applications_startup_idx on public.startup_applications (startup_id, created_at desc);

create table if not exists public.social_edges (
  source_user_id uuid references public.users(id) on delete cascade,
  target_user_id uuid references public.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (source_user_id, target_user_id)
);

create table if not exists public.user_employment (
  user_id uuid references public.users(id) on delete cascade,
  company text not null,
  role text,
  created_at timestamptz not null default now(),
  primary key (user_id, company)
);

create table if not exists public.interactions (
  id bigint generated by default as identity primary key,
  user_id uuid references public.users(id) on delete cascade,
  item_id text not null,
  item_type text not null,
  action text not null check (action in ('like','save','hide','apply','view','share')),
  dwell_ms int not null default 0,
  reason text,
  created_at timestamptz not null default now()
);
create index if not exists interactions_user_idx on public.interactions (user_id, created_at desc);

create table if not exists public.impressions (
  id bigint generated by default as identity primary key,
  impression_id text not null unique,
  user_id uuid references public.users(id) on delete cascade,
  item_id text not null,
  item_type text not null,
  rank_position int not null check (rank_position > 0),
  candidate_source text not null default 'feed',
  model_version text not null default 'rules-v1',
  surface text not null default 'feed',
  context jsonb not null default '{}',
  created_at timestamptz not null default now()
);
create index if not exists impressions_user_idx on public.impressions (user_id, created_at desc);

create table if not exists public.referral_requests (
  id bigint generated by default as identity primary key,
  requester_id uuid references public.users(id) on delete cascade,
  target_user_id uuid references public.users(id) on delete set null,
  job_id uuid references public.jobs(id) on delete set null,
  draft_hinglish text,
  draft_english text,
  status text not null default 'draft',
  created_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid references public.users(id) on delete cascade,
  title text not null,
  body text not null,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.agent_memory (
  user_id uuid references public.users(id) on delete cascade,
  memory_key text not null,
  memory_value jsonb not null,
  updated_at timestamptz not null default now(),
  primary key (user_id, memory_key)
);

